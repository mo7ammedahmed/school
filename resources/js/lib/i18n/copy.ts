export type CopyKey = keyof typeof en;

export type CopyParams = Record<string, string | number>;

function interpolate(template: string, params?: CopyParams): string {
    if (!params) return template;
    let out = template;
    for (const [key, value] of Object.entries(params)) {
        out = out.split(`{${key}}`).join(String(value));
    }
    return out;
}

/** Read the localised string for the active locale, interpolating any {params}. */
export function t(locale: Locale, key: CopyKey, params?: CopyParams): string {
    return interpolate(locale === 'ar' ? ar[key] : en[key], params);
}

/**
 * Like t(), but accepts runtime-built key strings and falls back to the raw
 * key when it is not in the dictionary (used for content that arrives as keys,
 * e.g. FAQ questions and facility copy).
 */
export function tk(locale: Locale, key: string, params?: CopyParams): string {
    const table = locale === 'ar' ? ar : en;
    const template = (key as CopyKey) in table ? table[key as CopyKey] : key;
    return interpolate(template, params);
}